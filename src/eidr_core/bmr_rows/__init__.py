"""BMR row helpers shared by the source tools that build inbound BMR sheets
(reconciliation component C2).

Ruled in eidr-core-ops ``PHASE2-3-INTERFACES-2026-10-15.md`` (C2,
2026-10-17). Routing is ``bmr_io.template_for_creation_type`` and writing is
``bmr_io.write_sheet``; this module holds what eidr-wikidata and eidr-imdb
each re-implemented around them:

* the two unconfirmed-ID columns of ruling R1, which replace
  ``Wikidata's EIDR ID`` (``Assigned EIDR ID`` stays empty: R2);
* ``number_families``: repeating families as numbered columns, extracted
  from eidr-imdb ``sheet.numbered`` (eidr-wikidata numbers inline);
* ``chunk_rows``: files the BMR tool can load, keeping each Series tree
  whole, extracted from eidr-wikidata ``_split_episodic`` /
  ``_split_non_episodic``. The limit is a GUIDELINE against the tool's
  memory errors, not a hard cutoff (operator, 2026-10-17: "The row limit is
  a function of how many optional columns are provided. With just a default
  template, you can go to 25,000 rows per sheet. With large rows (like those
  generated by Wikidata), it's safest to cut off at 5,000. (Going over 5K is
  fine -- it's not a hard cutoff, just a guideline)."). ``chunk_rows`` still
  closes a chunk before a tree that would overflow it, since that costs
  nothing; pass a larger ``limit`` for narrow rows;
* ``join_notes``: one separator for Operator's Notes, the ``SWAPPED:`` note
  first, because BMR-Review's control parses the opening of the cell.

and the row defaults the operator ruled on 2026-10-17:

* ``registrant_party``: the Registrant of an inbound row is the source's own
  Party ID when the source is an EIDR member (IMDb is: ``IMDB_PARTY``), and
  the EIDR Catalog party (``EIDR_CATALOG_PARTY``) for a non-member source
  such as Wikidata. **No Metadata Authority is written.**
* ``original_languages``: the work's languages, or ``und``; intertitles are
  language material, so a silent work keeps its language with mode Visual;
  ``zxx`` (no linguistic content) only for material with NO narrative
  language at all (actualities, stock footage).
* ``title_language``: ``und`` for a title with no stated language, nothing
  when there is no title.

The episodic ordering lands with the first adoption. Country of Origin is
``codes.country_list``.
"""
from __future__ import annotations

from collections.abc import Callable, Iterable, Mapping, Sequence
from typing import Any, TypeVar

from eidr_core.swap import SWAP_NOTE

__all__ = [
    "BMR_ROW_LIMIT",
    "EIDR_CATALOG_PARTY",
    "IMDB_PARTY",
    "NOTE_SEPARATOR",
    "REGISTRY_IDS_COLUMN",
    "SOURCE_ASSERTED_COLUMN",
    "UNCONFIRMED_ID_COLUMNS",
    "chunk_rows",
    "join_notes",
    "number_families",
    "original_languages",
    "registrant_party",
    "registry_ids_cell",
    "title_language",
]

# Ruling R1 (2026-10-14): appended after the template's columns.
SOURCE_ASSERTED_COLUMN = "Source-Asserted EIDR ID"   # Wikidata P2704; empty for IMDb
REGISTRY_IDS_COLUMN = "Registry EIDR ID(s)"          # records carrying the source ID
UNCONFIRMED_ID_COLUMNS = (SOURCE_ASSERTED_COLUMN, REGISTRY_IDS_COLUMN)

# Rows per file: the safe guideline for wide rows (operator, 2026-10-17); a
# default-template sheet can go to about 25,000. Not a hard cutoff.
BMR_ROW_LIMIT = 5_000

# Registrant parties (operator, 2026-10-17). IMDb is an EIDR member and has
# its own Party ID; a source that is not a member registers as the EIDR
# Catalog party. eidr-imdb carried IMDb's ID as "EIDR_PARTY" and also wrote
# it as Metadata Authority, which the same ruling drops.
IMDB_PARTY = "10.5237/27B2-6941"
EIDR_CATALOG_PARTY = "10.5237/FFDA-9947"

NOTE_SEPARATOR = " | "
_SWAP_PREFIX = SWAP_NOTE.split("{", 1)[0]            # "SWAPPED: asserted "

R = TypeVar("R")


def registry_ids_cell(eidr_ids: Iterable[str]) -> str:
    """The ``Registry EIDR ID(s)`` value: the IDs, de-duplicated, sorted,
    joined by ``" | "`` (R1). Sorted so the cell does not change with query
    order; pass ``lookup.claimants`` IDs, which already never choose one."""
    return NOTE_SEPARATOR.join(sorted({i.strip() for i in eidr_ids if i and i.strip()}))


def join_notes(*parts: str | None) -> str:
    """Operator's Notes from its parts: non-empty parts joined by ``" | "``,
    a ``SWAPPED:`` note moved first. eidr-imdb joined with ``" | "`` and
    eidr-wikidata with a space; one form, so a reader can split it."""
    kept = [p.strip() for p in parts if p and p.strip()]
    swapped = [p for p in kept if p.startswith(_SWAP_PREFIX)]
    return NOTE_SEPARATOR.join(swapped + [p for p in kept if p not in swapped])


def number_families(row: Mapping[str, Any],
                    family_members: Mapping[str, Sequence[str]]) -> dict[str, Any]:
    """The row with every family list expanded to ``"<Member> <n>"`` columns,
    the ``{column: value}`` shape ``bmr_io.write_sheet`` takes.

    ``family_members`` maps a key of ``row`` to the member headers its tuples
    fill, in order (``{"country": ("Country of Origin",)}``). Other keys pass
    through. Empty members are omitted, so the writer neither writes empty
    strings nor counts them toward the family's width.
    """
    out: dict[str, Any] = {}
    for key, value in row.items():
        members = family_members.get(key)
        if members is None:
            out[key] = value
            continue
        for i, group in enumerate(value or (), 1):
            for member, v in zip(members, group, strict=False):
                if v not in (None, ""):
                    out[f"{member} {i}"] = v
    return out


def chunk_rows(rows: Sequence[R], *, limit: int = BMR_ROW_LIMIT,
               starts_tree: Callable[[R], bool] | None = None) -> list[list[R]]:
    """Split rows into files of at most ``limit`` rows.

    Without ``starts_tree`` the rows are cut every ``limit`` rows. With it,
    a tree runs from a row it answers True for (a Series) up to the next one,
    and trees are never split: a chunk closes BEFORE a tree that would take
    it over the limit, so every chunk is at most ``limit`` rows except one
    holding a single tree that is itself larger (the caller can find those:
    ``len(chunk) > limit``). Rows before the first tree start (orphans) form
    a group of their own. The rows must already be in tree order.
    """
    if limit < 1:
        raise ValueError("limit must be at least 1")
    if not rows:
        return []
    if starts_tree is None:
        return [list(rows[i:i + limit]) for i in range(0, len(rows), limit)]
    trees: list[list[R]] = []
    for row in rows:
        if not trees or starts_tree(row):
            trees.append([])
        trees[-1].append(row)
    chunks: list[list[R]] = []
    current: list[R] = []
    for tree in trees:
        if current and len(current) + len(tree) > limit:
            chunks.append(current)
            current = []
        current.extend(tree)
    if current:
        chunks.append(current)
    return chunks


def registrant_party(member_party: str | None = None) -> str:
    """The Registrant for an inbound row: the source's own Party ID when the
    source is an EIDR member (``IMDB_PARTY`` for IMDb-sourced records), else
    ``EIDR_CATALOG_PARTY``. Inbound rows carry no Metadata Authority."""
    return (member_party or "").strip() or EIDR_CATALOG_PARTY


def original_languages(languages: Iterable[str] | None, *, silent: bool = False,
                       no_language_material: bool = False) -> list[tuple[str, str]]:
    """``(Original Language, Language Mode)`` pairs for one row.

    Operator, 2026-10-17: "If the show has intertitles, they count as
    language material (mode = Visual). Only use zxx (no linguistic content)
    for actualities (early silent films), stock footage, etc. where there is
    no narrative language material." So a silent work keeps its languages
    (the intertitles') with mode Visual, ``und`` when none is known; only
    ``no_language_material`` gives ``zxx``. A sound work's languages are
    Audio. eidr-wikidata wrote ``zxx`` for every silent work.
    """
    mode = "Visual" if silent else "Audio"
    if no_language_material:
        return [("zxx", mode)]
    langs: list[str] = []
    for lang in languages or ():
        code = (lang or "").strip()
        if code and code not in langs:
            langs.append(code)
    return [(code, mode) for code in (langs or ["und"])]


def title_language(title: str | None, language: str | None = None) -> str:
    """``Title Language``: the stated language, ``und`` for a title with
    none, and nothing when there is no title (``und`` means undetermined,
    not absent)."""
    if not (title or "").strip():
        return ""
    return (language or "").strip() or "und"
